const { chromium, expect } = require('@playwright/test');
const fs = require('fs');
let browser;
(async () => {
  const fixture = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
  browser = await chromium.launch({ channel: 'msedge' });
  const page = await browser.newPage({ viewport: { width: 1400, height: 900 } });
  const requests = [];
  page.on('request', r => requests.push({url:r.url(),method:r.method()}));
  await page.goto(fixture.url);
  const node = page.locator('.react-flow__node[data-id="skill"]');
  await node.waitFor({ timeout: 60000 });
  await node.click();
  const status = node.getByTestId('skill-discovery-status');
  const setSource = async source => {
    await node.getByTestId('popover-anchor-input-source').fill(source);
    await node.getByTestId('popover-anchor-input-source').press('Tab');
  };
  const selectSkill = async name => {
    await node.getByTestId('dropdown_str_skill_id').click();
    await page.getByRole('option', { name, exact: true }).click();
  };
  await setSource(fixture.local_source);
  await expect(status).toHaveText('2 skills discovered.', { timeout: 70000 });
  await node.getByTestId('dropdown_str_skill_id').click();
  await page.getByTestId('dropdown_search_input').fill('beta');
  await expect(page.getByRole('option', { name: 'beta | beta', exact: true })).toBeVisible();
  await expect(page.getByRole('option', { name: 'alpha | alpha', exact: true })).toHaveCount(0);
  await page.getByTestId('dropdown_search_input').fill('invented');
  await expect(page.getByRole('option', { name: /alpha|beta/ })).toHaveCount(0);
  await page.getByTestId('dropdown_search_input').fill('alpha');
  await page.getByRole('option', { name: 'alpha | alpha', exact: true }).click();
  await expect(status).toHaveText('2 revisions discovered.', { timeout: 70000 });
  await node.getByTestId('dropdown_str_revision_id').click();
  const revisions = await page.getByRole('option').allTextContents();
  const selected = revisions.find(x => x.includes('sha256:'));
  await page.getByTestId('dropdown_search_input').fill(selected.split('sha256:')[1].slice(0, 12));
  await expect(page.getByRole('option', { name: /sha256:/ })).toHaveCount(1);
  await page.getByRole('option', { name: selected, exact: true }).click();
  await expect(status).toHaveText('2 revisions discovered.', { timeout: 70000 });
  await page.getByTestId('skill-files-button').click();
  await expect(page.getByTestId('skill-selection')).toContainText(selected.split(' | ')[1]);
  await expect(page.locator('.monaco-editor .view-lines')).toContainText('alpha first snapshot', { timeout: 30000 });
  await page.keyboard.press('Escape');
  await selectSkill('beta | beta');
  await expect(status).toHaveText('1 revisions discovered.', { timeout: 70000 });
  await page.getByTestId('skill-files-button').click();
  await expect(page.getByRole('alert')).toContainText('Select a skill and revision first.');
  await expect(page.getByTestId('skill-file-source')).toHaveCount(0);
  await page.keyboard.press('Escape');
  await setSource(fixture.repository_source);
  await expect(status).toHaveText('1 skills discovered.', { timeout: 70000 });
  await selectSkill('alpha | alpha');
  await expect(status).toHaveText('2 revisions discovered.', { timeout: 70000 });
  await node.getByTestId('dropdown_str_revision_id').click();
  await page.getByTestId('dropdown_search_input').fill('tags/v1');
  const tag = page.getByRole('option', { name: /tags\/v1/ });
  await expect(tag).toHaveCount(1);
  const tagLabel = await tag.innerText();
  await tag.click();
  await expect(status).toHaveText('2 revisions discovered.', { timeout: 70000 });
  await page.getByTestId('skill-files-button').click();
  await expect(page.getByTestId('skill-selection')).toContainText(tagLabel.split(' | ')[1]);
  await expect(page.locator('.monaco-editor .view-lines')).toContainText('alpha first snapshot', { timeout: 30000 });
  await page.keyboard.press('Escape');
  // Hold an old response while a different source is selected.
  let release, observed;
  const held = new Promise(resolve => { release = resolve; });
  const seen = new Promise(resolve => { observed = resolve; });
  await page.route('**/api/v1/custom_component/update*', async route => {
    const body = route.request().postDataJSON();
    if (body.field === 'source' && body.field_value === fixture.local_source) {
      const response = await route.fetch(); observed(); await held;
      await route.fulfill({ response });
    } else await route.continue();
  });
  await setSource(fixture.local_source);
  await Promise.race([seen, new Promise((_, reject) => setTimeout(() => reject(Error("stale-request-not-observed")), 15000))]);
  await setSource(fixture.repository_source);
  await expect(status).toHaveText('1 skills discovered.', { timeout: 70000 });
  release();
  await page.waitForTimeout(1000);
  await expect(status).toHaveText('1 skills discovered.');
  await node.getByTestId('dropdown_str_skill_id').click();
  await expect(page.getByRole('option', { name: 'beta | beta', exact: true })).toHaveCount(0);
  await page.keyboard.press('Escape');
  await page.unroute('**/api/v1/custom_component/update*');
  await setSource('https://unapproved.invalid/skills');
  await expect(status).toHaveText('Discovery failed. Check source access and refresh.', { timeout: 70000 });
  await page.getByTestId('skill-files-button').click();
  await expect(page.getByRole('alert')).toContainText('Select a skill and revision first.');
  expect(requests.filter(r => r.method === 'POST' && /\/build|\/runs|\/publish/.test(new URL(r.url).pathname))).toEqual([]);
  console.log('PASS: local and Git fixture discovery, typed filters, immutable inspection, resets, stale response and access failure; no execution.');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { if (browser) await browser.close(); });
